#!/usr/bin/env node
// Regenerates catalogImages.ts from whatever PNGs exist in assets/catalog/.
// Run after the Magnific batch: node gen-image-map.js
const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, 'assets', 'catalog');
const ids = fs.existsSync(dir)
  ? fs.readdirSync(dir).filter((f) => f.endsWith('.png')).map((f) => f.replace('.png', '')).sort()
  : [];

const lines = ids.map((id) => `  ${id}: require('./assets/catalog/${id}.png'),`);
const out = `// AUTO-GENERATED by gen-image-map.js — do not edit by hand.
// Ghost-mannequin product shots (Magnific). Missing SKUs fall back to swatch+glyph.

export const IMAGES: Record<string, number> = {
${lines.join('\n')}
};
`;
fs.writeFileSync(path.join(__dirname, 'catalogImages.ts'), out);
console.log(`catalogImages.ts: ${ids.length} images mapped`);
